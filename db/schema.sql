CREATE TABLE IF NOT EXISTS users (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nickname TEXT NOT NULL UNIQUE,
    email TEXT NOT NULL UNIQUE,
    password_hash TEXT NOT NULL,
    role TEXT NOT NULL DEFAULT 'user' CHECK (role IN ('user','author','admin')),
    email_verified INTEGER NOT NULL DEFAULT 0 CHECK (email_verified IN (0,1)),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS patches (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version TEXT NOT NULL UNIQUE,
    release_date DATE NOT NULL,
    summary TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS heroes (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL UNIQUE,
    slug TEXT NOT NULL UNIQUE,
    primary_attribute TEXT NOT NULL CHECK (primary_attribute IN ('Сила','Ловкость','Интеллект','Универсальный')),
    attack_type TEXT NOT NULL CHECK (attack_type IN ('Ближний бой','Дальний бой')),
    roles TEXT NOT NULL,
    base_health INTEGER NOT NULL CHECK (base_health >= 0),
    base_mana INTEGER NOT NULL CHECK (base_mana >= 0),
    armor REAL NOT NULL DEFAULT 0 CHECK (armor >= 0),
    lore TEXT NOT NULL,
    image_url TEXT
);

CREATE TABLE IF NOT EXISTS abilities (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    hero_id INTEGER NOT NULL REFERENCES heroes(id) ON DELETE CASCADE,
    name TEXT NOT NULL,
    ability_type TEXT NOT NULL CHECK (ability_type IN ('Активная','Пассивная','Ультимативная','Улучшение')),
    description TEXT NOT NULL,
    mana_cost TEXT NOT NULL DEFAULT '—',
    cooldown TEXT NOT NULL DEFAULT '—',
    levels_json TEXT NOT NULL DEFAULT '[]',
    position INTEGER NOT NULL DEFAULT 1,
    UNIQUE(hero_id, name)
);

CREATE TABLE IF NOT EXISTS talents (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    hero_id INTEGER NOT NULL REFERENCES heroes(id) ON DELETE CASCADE,
    level INTEGER NOT NULL CHECK (level IN (10,15,20,25)),
    left_talent TEXT NOT NULL,
    right_talent TEXT NOT NULL,
    UNIQUE(hero_id, level)
);

CREATE TABLE IF NOT EXISTS items (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL UNIQUE,
    slug TEXT NOT NULL UNIQUE,
    cost INTEGER NOT NULL CHECK (cost >= 0),
    category TEXT NOT NULL,
    description TEXT NOT NULL,
    bonuses TEXT NOT NULL DEFAULT '',
    effect TEXT NOT NULL DEFAULT ''
);

CREATE TABLE IF NOT EXISTS item_recipes (
    item_id INTEGER NOT NULL REFERENCES items(id) ON DELETE CASCADE,
    component_item_id INTEGER NOT NULL REFERENCES items(id) ON DELETE RESTRICT,
    quantity INTEGER NOT NULL DEFAULT 1 CHECK (quantity > 0),
    PRIMARY KEY(item_id, component_item_id),
    CHECK (item_id <> component_item_id)
);

CREATE TABLE IF NOT EXISTS patch_changes (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patch_id INTEGER NOT NULL REFERENCES patches(id) ON DELETE CASCADE,
    hero_id INTEGER REFERENCES heroes(id) ON DELETE SET NULL,
    ability_id INTEGER REFERENCES abilities(id) ON DELETE SET NULL,
    item_id INTEGER REFERENCES items(id) ON DELETE SET NULL,
    change_type TEXT NOT NULL CHECK (change_type IN ('Усиление','Ослабление','Переработка','Исправление')),
    description TEXT NOT NULL,
    CHECK (((hero_id IS NOT NULL)::int + (ability_id IS NOT NULL)::int + (item_id IS NOT NULL)::int) = 1)
);

CREATE TABLE IF NOT EXISTS guides (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    author_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    hero_id INTEGER NOT NULL REFERENCES heroes(id) ON DELETE CASCADE,
    patch_id INTEGER NOT NULL REFERENCES patches(id) ON DELETE RESTRICT,
    title TEXT NOT NULL,
    role TEXT NOT NULL,
    description TEXT NOT NULL,
    skill_build_json TEXT NOT NULL DEFAULT '[]',
    talent_build_json TEXT NOT NULL DEFAULT '{}',
    rating REAL NOT NULL DEFAULT 0 CHECK (rating BETWEEN 0 AND 5),
    status TEXT NOT NULL DEFAULT 'draft' CHECK (status IN ('draft','pending','published','rejected')),
    views INTEGER NOT NULL DEFAULT 0 CHECK (views >= 0),
    is_outdated INTEGER NOT NULL DEFAULT 0 CHECK (is_outdated IN (0,1)),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS guide_items (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    guide_id INTEGER NOT NULL REFERENCES guides(id) ON DELETE CASCADE,
    item_id INTEGER NOT NULL REFERENCES items(id) ON DELETE RESTRICT,
    game_stage TEXT NOT NULL CHECK (game_stage IN ('Старт','Ранняя игра','Середина игры','Поздняя игра')),
    position INTEGER NOT NULL DEFAULT 1,
    UNIQUE(guide_id, game_stage, position)
);

CREATE TABLE IF NOT EXISTS comments (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    guide_id INTEGER NOT NULL REFERENCES guides(id) ON DELETE CASCADE,
    body TEXT NOT NULL CHECK (length(trim(body)) > 0),
    is_hidden INTEGER NOT NULL DEFAULT 0 CHECK (is_hidden IN (0,1)),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS favorites (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    hero_id INTEGER REFERENCES heroes(id) ON DELETE CASCADE,
    item_id INTEGER REFERENCES items(id) ON DELETE CASCADE,
    guide_id INTEGER REFERENCES guides(id) ON DELETE CASCADE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK (((hero_id IS NOT NULL)::int + (item_id IS NOT NULL)::int + (guide_id IS NOT NULL)::int) = 1),
    UNIQUE(user_id, hero_id),
    UNIQUE(user_id, item_id),
    UNIQUE(user_id, guide_id)
);

CREATE INDEX IF NOT EXISTS idx_abilities_hero ON abilities(hero_id);
CREATE INDEX IF NOT EXISTS idx_patch_changes_patch ON patch_changes(patch_id);
CREATE INDEX IF NOT EXISTS idx_guides_status ON guides(status);
CREATE INDEX IF NOT EXISTS idx_guides_hero ON guides(hero_id);
CREATE INDEX IF NOT EXISTS idx_favorites_user ON favorites(user_id);

